import {fileURLToPath} from 'node:url'
const OUT=fileURLToPath(new URL('.',import.meta.url)).replaceAll('\\','/').replace(/\/$/,'')
const BASE_URL=process.env.BASE_URL || 'http://127.0.0.1:4319'
import {chromium} from 'playwright'
import {readFile,writeFile} from 'node:fs/promises'
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1365,height:900},acceptDownloads:true})
const errors=[],requests=[]
page.on('pageerror',error=>errors.push(error.message))
await page.addInitScript(()=>{
 if(sessionStorage.getItem('seeded'))return
 sessionStorage.setItem('seeded','1')
 const messages=Array.from({length:40},(_,i)=>({role:i%2?'assistant':'user',content:`${i%2?'Reply':'Prompt'} ${i}: `+'Evidence and useful context. '.repeat(14)}))
 messages.push({role:'assistant',content:'| Name | Value |\n|---|---|\n| Việt, "quoted" | =SUM(A1) |'})
 localStorage.setItem('ods.pixel.chat.v1',JSON.stringify({schema:1,chatId:'batch-browser',messages,draft:''}))
 localStorage.setItem('ods.pixel.saved-prompts.v1',JSON.stringify([{id:'prompt-original',title:'Keep evidence',text:'Review the actual result.'}]))
})
await page.route('**/api/**',async route=>{
 const path=new URL(route.request().url()).pathname
 if(route.request().method()!=='GET')requests.push(path)
 if(path==='/api/pixel/chat/stream')return route.fulfill({contentType:'text/event-stream',body:'data: {"choices":[{"delta":{"content":"Fresh streaming result"}}]}\n\ndata: [DONE]\n\n'})
 const body=path==='/api/pixel/status'?{available:true,model:'pixel/default',runtime:{model:'private-model-name',contextLength:8192}}
 :path==='/api/status'?{services:[],inference:{loadedModel:'private-model-name',contextSize:32768},secret:'never-export'}
 :path.endsWith('access-mode')?{available:true,configured_mode:'full-access',effective_mode:'sandboxed',runtime_verified:true,privateKey:'never-export'}
 :path==='/api/pixel/identity'?{schemaVersion:1,revision:0,displayName:'Portal'}
 :path==='/api/setup/status'?{first_run:false,setup_complete:true}:{}
 return route.fulfill({contentType:'application/json',body:JSON.stringify(body)})
})
try{
 await page.goto(BASE_URL + '/')
 const input=page.getByPlaceholder('Message Portal...')
 await input.waitFor()
 const csvEvent=page.waitForEvent('download')
 await page.getByRole('button',{name:'Download table CSV'}).click()
 const csv=await readFile(await (await csvEvent).path(),'utf8')
 if(!csv.includes('"Việt, ""quoted""","\'=SUM(A1)"'))throw new Error('CSV bytes incorrect: '+csv)
 const region=page.getByRole('region',{name:'Conversation messages'})
 await region.evaluate(el=>{el.scrollTop=300;el.dispatchEvent(new Event('scroll'))})
 await page.getByRole('button',{name:'Jump to latest',exact:true}).waitFor()
 const before=await region.evaluate(el=>el.scrollTop)
 await input.fill('Continue from here')
 await input.press('Enter')
 await page.getByText('Fresh streaming result',{exact:true}).waitFor({state:'attached'})
 await page.waitForTimeout(250)
 const after=await region.evaluate(el=>el.scrollTop)
 if(Math.abs(before-after)>2)throw new Error(`Reading position moved ${before} -> ${after}`)
 await page.getByRole('button',{name:'Jump to latest',exact:true}).click()
 const distance=await region.evaluate(el=>el.scrollHeight-el.clientHeight-el.scrollTop)
 if(distance>65)throw new Error('Jump failed: '+distance)
 await page.getByRole('button',{name:'Search Pixel',exact:true}).click()
 await page.getByLabel('Search conversations and actions').fill('Fresh streaming result')
 await page.getByRole('dialog',{name:'Search Pixel'}).getByText(/Reply: Fresh streaming result/).waitFor()
 await page.getByRole('button',{name:'Close search',exact:true}).click()
 await input.fill('Check useful context')
 await page.getByLabel('Chat options',{exact:true}).click()
 await page.getByRole('button',{name:'Request context',exact:true}).click()
 await page.getByRole('region',{name:'Next request context'}).waitFor()
 await page.screenshot({path:OUT + '/batch-context-desktop.png'})
 await page.getByLabel('Chat options',{exact:true}).click()
 await page.getByRole('button',{name:'Saved prompts',exact:true}).click()
 await page.getByLabel('Import prompt backup',{exact:true}).setInputFiles({name:'prompts.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({schemaVersion:1,kind:'ods-pixel-prompts',prompts:[{title:'Keep evidence',text:'Review the actual result.'},{title:'New review',text:'Exact Việt\r\ntext'}]}))})
 await page.getByRole('button',{name:'Confirm prompt import'}).click()
 if(await input.inputValue()!=='Check useful context')throw new Error('Import changed the draft')
 const backupEvent=page.waitForEvent('download')
 await page.getByRole('button',{name:'Download prompt backup'}).click()
 const backup=JSON.parse(await readFile(await (await backupEvent).path(),'utf8'))
 if(backup.prompts.length!==2||backup.prompts[1].text!=='Exact Việt\r\ntext')throw new Error('Prompt round trip failed')
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:OUT + '/batch-prompts-mobile.png'})
 const dialog=await page.getByRole('dialog',{name:'Saved prompts'}).boundingBox()
 if(dialog.x<0||dialog.x+dialog.width>391||dialog.height>844)throw new Error('Prompt dialog overflow')
 await page.getByRole('button',{name:'Close prompts'}).click()
 await page.getByLabel('Choose text file').setInputFiles({name:'context.md',mimeType:'text/markdown',buffer:Buffer.from('# Local context\n\n- Retain Unicode Việt')})
 await page.getByRole('button',{name:'Insert file text'}).click()
 await page.getByRole('button',{name:'Preview draft',exact:true}).click()
 await page.screenshot({path:OUT + '/batch-composer-mobile.png'})
 await page.getByRole('button',{name:'Hide draft preview'}).click()
 await page.getByLabel('Chat options',{exact:true}).click()
 await page.screenshot({path:OUT + '/batch-context-mobile.png'})
 const menu=await page.locator('.pixel-chat-options-menu').boundingBox()
 if(menu.x<0||menu.x+menu.width>391||menu.y+menu.height>845)throw new Error('Options menu overflow '+JSON.stringify(menu))
 await page.goto(BASE_URL + '/pixel/settings?section=pixel-diagnostics')
 const summary=page.getByRole('button',{name:'Download check summary'})
 await summary.waitFor()
 const summaryEvent=page.waitForEvent('download')
 await summary.click()
 const summaryText=await readFile(await (await summaryEvent).path(),'utf8')
 const report=JSON.parse(summaryText)
 if(report.kind!=='ods-pixel-diagnostic-summary'||summaryText.includes('private-model')||summaryText.includes('never-export'))throw new Error('Diagnostic allowlist failed')
 await page.screenshot({path:OUT + '/batch-diagnostics-mobile.png'})
 const result={passed:true,readingPosition:{before,after,distance},csv:true,promptRoundTrip:true,diagnosticAllowlist:true,mobileBounds:true,errors,requests}
 await writeFile(OUT + '/batch-browser-result.json',JSON.stringify(result,null,2))
 console.log(JSON.stringify(result))
 if(errors.length)throw new Error('Browser errors')
}finally{await browser.close()}
